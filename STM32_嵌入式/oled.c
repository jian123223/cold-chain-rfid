// ========== 8×8小字显示函数 ==========
// ========== 8×8小字显示函数 ==========
void OLED_ShowChar8(uint8_t Y, uint8_t X, char Char)
{
	uint16_t idx = Char - ' ';
	if(idx > 95) idx = 0;
	OLED_SetCursor(Y, X << 3);
	uint8_t i;
	for(i = 0; i < 8; i++)
		OLED_WriteData(OLED_F8x8[idx * 8 + i]);
}

void OLED_ShowString8(uint8_t Y, uint8_t X, char *String)
{
	uint8_t i;
	for(i = 0; String[i] != '\0'; i++)
	{
		if(X + i >= OLED_LINE_LEN_SMALL) break;
		OLED_ShowChar8(Y, X + i, String[i]);
	}
}

// 8行日志滚动
void OLED_AppendSmallLog(char *str)
{
	uint8_t i;
	for(i = 0; i < OLED_LINE_NUM_SMALL - 1; i++)
		strcpy(oled_small_buf[i], oled_small_buf[i+1]);
	strncpy(oled_small_buf[OLED_LINE_NUM_SMALL - 1], str, OLED_LINE_LEN_SMALL);
	oled_small_buf[OLED_LINE_NUM_SMALL - 1][OLED_LINE_LEN_SMALL] = '\0';
}

