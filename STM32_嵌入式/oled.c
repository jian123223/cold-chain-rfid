void OLED_ShowChinese16(uint8_t page, uint8_t col, uint8_t idx)
{
	uint8_t i;
	OLED_SetCursor(page, col);
	for(i = 0; i < 16; i++)
		OLED_WriteData(OLED_F16x16[idx][i]);
	OLED_SetCursor(page + 1, col);
	for(i = 0; i < 16; i++)
		OLED_WriteData(OLED_F16x16[idx][16 + i]);
}

void OLED_ClearLine8(uint8_t Y)
{
	OLED_SetCursor(Y, 0);
	uint8_t x;
	for(x = 0; x < 128; x++)
		OLED_WriteData(0x00);
}
